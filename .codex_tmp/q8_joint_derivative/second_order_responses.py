"""Audited second-order inverse-metric responses used by the q=8 notebook.

This module contains the spatial (Stage-1) subset of the corrected harmonic
coordinate transformation:

- three spatial accelerations,
- six components of the symmetric spatial-strain rate,
- five components of the physical electric STF tensor, and
- fifteen spatial harmonic quadrupoles.

It also contains the known quadratic source generated by the first-order
time-gradient ``beta`` and spatial strain.  The formulas are transcribed from
the corrected q=4 audit notebook.
"""

from __future__ import annotations

import numpy as np
from scipy.special import spence


def orthonormal_stf_basis() -> np.ndarray:
    """Return an orthonormal Cartesian STF basis."""
    basis = [
        np.diag([1.0, -1.0, 0.0]) / np.sqrt(2.0),
        np.diag([1.0, 1.0, -2.0]) / np.sqrt(6.0),
    ]
    for i, j in ((0, 1), (0, 2), (1, 2)):
        tensor = np.zeros((3, 3))
        tensor[i, j] = tensor[j, i] = 1.0 / np.sqrt(2.0)
        basis.append(tensor)
    return np.asarray(basis)


def orthonormal_symmetric_basis() -> np.ndarray:
    """Return an orthonormal Cartesian symmetric-matrix basis."""
    basis = []
    for i in range(3):
        tensor = np.zeros((3, 3))
        tensor[i, i] = 1.0
        basis.append(tensor)
    for i, j in ((0, 1), (0, 2), (1, 2)):
        tensor = np.zeros((3, 3))
        tensor[i, j] = tensor[j, i] = 1.0 / np.sqrt(2.0)
        basis.append(tensor)
    return np.asarray(basis)


